//! Показывает компоненты рабочего окна GPUI на фиксированных примерах.
//! Галерея хранит выбранные строки и черновики только в памяти окна.

#[cfg(target_os = "macos")]
mod gallery;

/// Запускает отдельное окно компонентов на macOS.
#[cfg(target_os = "macos")]
fn main() {
    gallery::run();
}

/// Сообщает об ограничении запуска на других платформах.
#[cfg(not(target_os = "macos"))]
fn main() {
    eprintln!("Галерея GPUI запускается на macOS");
}
